"""
repair_sessions
===============

Reviews sessions for a given date range against the active Schedule records
and corrects any discrepancies:

  - Creates sessions that are missing (slot exists in schedule but no Session row)
  - Deletes sessions that are out-of-schedule (Session row exists but does not
    match any slot generated by the current Schedule, or the date has no schedule)

Safe to run repeatedly — creation uses get_or_create.

Usage
-----
    python manage.py repair_sessions --start 2026-06-10 --end 2026-06-12

Or call the core function directly from other code:
    from Main.management.commands.repair_sessions import repair_sessions_for_range
"""

import logging
from datetime import datetime, timedelta, date

from django.core.management.base import BaseCommand
from django.utils import timezone

from Main.models.models_sessions import Schedule, Product, Session

logger = logging.getLogger(__name__)


def _expected_slots(product, target_date):
    """
    Return a list of (start_dt, end_dt) aware datetimes that the current
    Schedule says should exist for *product* on *target_date*.
    Returns an empty list when no schedule covers that weekday.
    """
    weekday = target_date.strftime('%A')
    schedule = Schedule.objects.filter(product=product, weekday=weekday).first()

    if not schedule or not schedule.start_time or not schedule.end_time:
        return []

    except_hours = set(schedule.except_hours or [])

    slots = []
    current = timezone.make_aware(datetime.combine(target_date, schedule.start_time))
    day_end = timezone.make_aware(datetime.combine(target_date, schedule.end_time))

    while current <= day_end:
        slot_end = current + product.duration
        if str(current.time()) not in except_hours:
            slots.append((current, slot_end))
        current = slot_end

    return slots


def repair_sessions_for_range(start_date, end_date, product_ids=None, dry_run=False):
    """
    Review every product (or only those in *product_ids*) for each date in
    [start_date, end_date] and:
      - Create any missing sessions.
      - Delete any sessions whose start_time does not belong to the current schedule.

    Returns a dict with keys: created, deleted, errors.
    """
    if isinstance(start_date, datetime):
        start_date = start_date.date()
    if isinstance(end_date, datetime):
        end_date = end_date.date()

    products = Product.objects.all()
    if product_ids:
        products = products.filter(id__in=product_ids)

    total_created = 0
    total_deleted = 0
    total_errors = 0

    for product in products:
        if not product.duration:
            logger.warning("Skipping product %s (%s): duration is zero", product.id, product.name)
            continue

        current_date = start_date
        while current_date <= end_date:
            try:
                expected = _expected_slots(product, current_date)

                # Build a set of expected start_times for fast lookup
                expected_starts = {s[0] for s in expected}

                # Day boundaries in aware datetimes
                day_start_aware = timezone.make_aware(datetime.combine(current_date, datetime.min.time()))
                day_end_aware = timezone.make_aware(datetime.combine(current_date, datetime.max.time()))

                existing_sessions = Session.objects.filter(
                    product=product,
                    start_time__gte=day_start_aware,
                    start_time__lte=day_end_aware,
                )

                existing_starts = {s.start_time for s in existing_sessions}

                # --- Delete out-of-schedule sessions ---
                to_delete = [s for s in existing_sessions if s.start_time not in expected_starts]
                for session in to_delete:
                    # Only delete if no bookings exist for this session
                    has_bookings = session.booking_set.filter(
                        status__in=['pending', 'done', 'hold']
                    ).exists()
                    if has_bookings:
                        logger.warning(
                            "Skipping delete of session %s (product=%s, start=%s): has active bookings",
                            session.id, product.name, session.start_time,
                        )
                        continue
                    logger.info(
                        "DELETE session %s | product=%s | %s",
                        session.id, product.name, session.start_time,
                    )
                    if not dry_run:
                        session.delete()
                    total_deleted += 1

                # --- Create missing sessions ---
                for start_dt, end_dt in expected:
                    if start_dt not in existing_starts:
                        logger.info(
                            "CREATE session | product=%s | %s → %s",
                            product.name, start_dt, end_dt,
                        )
                        if not dry_run:
                            Session.objects.get_or_create(
                                product=product,
                                start_time=start_dt,
                                end_time=end_dt,
                                defaults={
                                    'available_seats': product.max_num,
                                    'weekday': start_dt.strftime('%A'),
                                },
                            )
                        total_created += 1

            except Exception as exc:
                total_errors += 1
                logger.exception(
                    "repair_sessions error for product %s on %s: %s",
                    product.id, current_date, exc,
                )

            current_date += timedelta(days=1)

    logger.info(
        "repair_sessions complete | created=%d | deleted=%d | errors=%d | dry_run=%s",
        total_created, total_deleted, total_errors, dry_run,
    )
    return {"created": total_created, "deleted": total_deleted, "errors": total_errors}


class Command(BaseCommand):
    help = 'Repair sessions for a date range: creates missing, deletes out-of-schedule.'

    def add_arguments(self, parser):
        parser.add_argument('--start', required=True, help='Start date YYYY-MM-DD')
        parser.add_argument('--end', required=True, help='End date YYYY-MM-DD')
        parser.add_argument(
            '--products', nargs='*', type=int,
            help='Optional list of product IDs to limit scope'
        )
        parser.add_argument(
            '--dry-run', action='store_true',
            help='Log what would happen without making any DB changes'
        )

    def handle(self, *args, **options):
        try:
            start_date = date.fromisoformat(options['start'])
            end_date = date.fromisoformat(options['end'])
        except ValueError as exc:
            self.stderr.write(f"Invalid date format: {exc}")
            return

        if start_date > end_date:
            self.stderr.write("--start must be <= --end")
            return

        result = repair_sessions_for_range(
            start_date=start_date,
            end_date=end_date,
            product_ids=options.get('products'),
            dry_run=options['dry_run'],
        )
        self.stdout.write(
            f"Done. created={result['created']} deleted={result['deleted']} errors={result['errors']}"
            + (" [DRY RUN]" if options['dry_run'] else "")
        )
